    public function run(): void
    {
        foreach ($this->areas() as $position => $area) {
            $careers = $area['careers'];
            unset($area['careers']);

            $areaModel = Area::updateOrCreate(['slug' => $area['slug']], [...$area, 'position' => $position]);

            foreach ($careers as $career) {
                $steps = $career['steps'];
                unset($career['steps']);

                $careerModel = Career::updateOrCreate(['slug' => $career['slug']], [...$career, 'area_id' => $areaModel->id]);

                if ($careerModel->steps()->exists()) {
                    continue;
                }

                foreach ($steps as $index => [$level, $title, $description]) {
                    $careerModel->steps()->create([
                        'level' => $level,
                        'title' => $title,
                        'description' => $description,
                        'position' => $index,
                    ]);
                }
            }
        }
    }

